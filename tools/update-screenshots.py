"""Rewrites data/screenshots.js from the image files in screenshots/.

Run from anywhere:  py tools/update-screenshots.py
"""
import json
import pathlib

SITE = pathlib.Path(__file__).resolve().parent.parent
EXTS = {".png", ".jpg", ".jpeg", ".gif", ".webp"}

files = sorted(
    (p for p in (SITE / "screenshots").iterdir() if p.suffix.lower() in EXTS),
    key=lambda p: p.name.lower(),
)
lines = []
for p in files:
    title = p.stem.replace("_", " ").replace("-", " ").strip()
    entry = {"file": p.name, "title": title}
    lines.append("  " + json.dumps(entry, ensure_ascii=False) + ",")

(SITE / "data" / "screenshots.js").write_text(
    "/*\n"
    " * Screenshots shown in the \"Screenshots\" window.\n"
    " * Generated by tools/update-screenshots.py from the files in screenshots/.\n"
    " * \"file\" is relative to screenshots/, \"title\" is the caption.\n"
    " */\n"
    "window.AMIJA_SCREENSHOTS = [\n" + "\n".join(lines) + ("\n" if lines else "") + "];\n",
    encoding="utf-8",
    newline="\n",
)
print(f"{len(files)} screenshot(s) listed in data/screenshots.js")
