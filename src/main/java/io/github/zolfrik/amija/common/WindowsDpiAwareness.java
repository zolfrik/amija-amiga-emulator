package io.github.zolfrik.amija.common;

import java.lang.foreign.Arena;
import java.lang.foreign.FunctionDescriptor;
import java.lang.foreign.Linker;
import java.lang.foreign.MemorySegment;
import java.lang.foreign.SymbolLookup;
import java.lang.foreign.ValueLayout;
import java.lang.invoke.MethodHandle;

/**
 * Declares the process <em>per-monitor DPI aware</em> on Windows, through
 * {@code user32!SetProcessDpiAwarenessContext} (Foreign Function API, like
 * {@link WindowsKeyState}).
 *
 * <p>Must be called as the <b>first</b> statement of {@code main()}, before the AWT toolkit
 * initialises: it is a correction of <em>timing</em>, not of value. AWT declares
 * {@code PER_MONITOR_AWARE_V2} by itself when it starts anyway, so the final state of the
 * process is identical either way; what changes is when it happens.
 *
 * <p><b>Why it is needed.</b> {@code java.exe}/{@code javaw.exe} carry a manifest with
 * {@code dpiAware=true/PM}, so the process is DPI aware from the first statement: launching
 * the jar is fine. The native launcher generated by jpackage has <b>no manifest</b>: the
 * process starts {@code DPI_UNAWARE} and is promoted only later, during the AWT init. In that
 * window AWT takes the system fonts ({@code win.defaultGUI.font}, {@code win.icon.font}, ...) at
 * 96 DPI. When something later triggers a re-read of those desktop properties (in practice the
 * first {@code JFileChooser}, which initialises the Windows shell) the OS returns them at the
 * real DPI and the fonts of the <b>whole</b> Look and Feel jump at once to the desktop's scale
 * factor (with a display at 150%: Tahoma 11 -> 16, Segoe UI 12 -> 18). The effect is permanent:
 * from then on every component created or re-measured is oversized.
 *
 * <p>Declaring the awareness before AWT makes the initial snapshot already right and the
 * re-read changes nothing.
 *
 * <p>On non-Windows platforms, on Windows older than 10 1703 (where the symbol does not exist)
 * or if native access is denied, the method is a silent no-op. It is also one under
 * {@code java.exe}, where the call fails with {@code ERROR_ACCESS_DENIED} because the
 * awareness is already set by the manifest.
 */
public final class WindowsDpiAwareness {

    /** {@code DPI_AWARENESS_CONTEXT_PER_MONITOR_AWARE_V2} (WinUser.h): pseudo-handle -4. */
    private static final long PER_MONITOR_AWARE_V2 = -4L;

    private WindowsDpiAwareness() {}

    /**
     * Declares the process per-monitor DPI aware (V2), if it is not already.
     *
     * @return true if this call actually set the awareness; false if it was already set or
     *         the call is not available.
     */
    public static boolean ensurePerMonitorAware() {
        String os = System.getProperty("os.name", "").toLowerCase(java.util.Locale.ROOT);
        if (!os.contains("win")) {
            return false;
        }
        try {
            Linker linker = Linker.nativeLinker();
            SymbolLookup user32 = SymbolLookup.libraryLookup("user32", Arena.global());
            MethodHandle setContext = linker.downcallHandle(
                    user32.find("SetProcessDpiAwarenessContext").orElseThrow(),
                    FunctionDescriptor.of(ValueLayout.JAVA_INT, ValueLayout.ADDRESS));
            return (int) setContext.invoke(MemorySegment.ofAddress(PER_MONITOR_AWARE_V2)) != 0;
        } catch (Throwable t) {
            // Symbol missing, native access denied, etc.: carry on without it.
            return false;
        }
    }
}
