    /**
     * One round of the stopped CPU. The grid is 4 CPU clocks, anchored at the start of the
     * STOP instruction ({@link #beginStopRounds()}), whose first round is opened there.
     */
    private void serviceStopRound() {
        if (((totalCycles - stopRoundAnchor) & 3) != 0) return;
        // End of the previous round: the IPL fetched at its start is recognised, then the
        // deferred value moves up.
        stoppedRecogIpl = stopIpl0;
        stopIpl0 = stopIpl1;
        stopIpl1 = 0;
        // Start of the next round: a new IPL fetch.
        int v = iplFetchNextValue();
        if (v < 0) stopIpl1 = iplPin;
        else { stopIpl0 = v; stopIpl1 = 0; }
        checkInterrupts();
    }
    private void checkInterrupts() {
        // The now/next selection can be made only here, at the boundary, because only here
        // is the poll-to-end distance known (see resolveIplAtBoundary).
        if (cpuState == CpuState.NORMAL) resolveIplAtBoundary();
        // NORMAL path (instruction boundary): uses the value sampled at the poll point (last
        // prefetch). STOPPED path: uses the value delayed by the IPL pipe (sync(2), i.e.
        // recognised on the previous poll), NOT the live pin; see the STOPPED branch of
        // risingEdge and stoppedRecogIpl.
        int ipl = (cpuState == CpuState.NORMAL) ? polledIpl
                : (cpuState == CpuState.STOPPED ? stoppedRecogIpl : latchedIpl);
        // Level 7 is an NMI but needs edge detection: it is accepted only if level7EdgeArmed
        // is true (IPL has dropped below 7 since the last NMI was served). The other levels
        // only have to exceed the current mask.
        if (ipl == 7 && !level7EdgeArmed) return;
        if (ipl > getIntMask() || ipl == 7) {
            if (!iackInProgress && ipl != 0 && cpuState != CpuState.EXCEPTION) {
                savedSR = getSR();
                iackInProgress = true;
                acknowledgedIpl = ipl;
                // Consume the level-7 edge: not accepted again until IPL drops.
                if (ipl == 7) level7EdgeArmed = false;
                enqueueBusOp(createInterruptAckOp(ipl));
            }
        }
    }
    private void finishIackAndStartException() {
        iackInProgress = false;
        cancelLoopMode();
        if (busResp.berr) exceptionVector = 24;
        else if (busResp.iackAutovector || busResp.vpa) exceptionVector = 24 + acknowledgedIpl;
        else if (busResp.iackVectorProvided) exceptionVector = busResp.iackVectorNumber & 0xFF;
        else exceptionVector = latchedBusData & 0xFF;
        exceptionPC = getPC();
        cpuState = CpuState.EXCEPTION;
        currentMicroTask = InternalTask.EXCEPTION_INTERRUPT;
        microTaskStep = 0;
    }
