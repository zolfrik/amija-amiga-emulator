    // =========================================================================
    // tempRegs: validity mask instead of a per-instruction clear
    // =========================================================================
    //
    // Clearing tempRegs at the start of EVERY instruction (`Arrays.fill(tempRegs, 0)`, 32
    // stores x ~10M instructions per 150M cycles) cost 3.6% of the profile. It was not dead
    // code: many instructions **read slots never written** and rely on the 0. The usual
    // idiom is
    //
    //     calculateEA(..., getTemp(cpu, EXT1), getTemp(cpu, EXT2), ...)
    //
    // where Java always evaluates the arguments, even for addressing modes with no
    // extension words (calculateEA then ignores the value). Some 30 instruction classes do
    // it: ADD, ADDA, ADDI, ADDQ, AND, ANDI, ASL/ASR, BCHG/BCLR/BSET/BTST, CHK, CLR, CMP,
    // CMPA, CMPI, DIVS/DIVU, EOR, EORI, JMP, JSR, LEA, LSL/LSR, MOVE, MOVEM, ...
    //
    // Rather than a guard in each of them, the guarantee is centralised here: a 32-bit mask
    // marks which slots the current instruction has written, and reading a slot not
    // written returns 0, exactly what the clear did. The equivalence holds **by
    // construction**, for every slot and every instruction, and the cost per instruction
    // drops from 32 stores to one.
    int tempRegsWritten;

    public int getTempReg(int index) {
        return (tempRegsWritten & (1 << index)) != 0 ? tempRegs[index] : 0;
    }

    public void setTempReg(int index, int value) {
        tempRegsWritten |= (1 << index);
        tempRegs[index] = value;
    }
