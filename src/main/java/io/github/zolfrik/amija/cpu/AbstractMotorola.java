    /**
     * Group 0 PC offset for a fault on a <b>data access</b>.
     *
     * <p>{@code 2 + 2*(extension words consumed) + delta}, where the delta depends on the
     * mode of the failing EA. Checked on <b>902 of the 906</b> data-access fault sites of
     * the 68000 instruction set; the 4 left over are MOVEM to registers with an indexed
     * mode, which declares its own.
     *
     * <p>The SingleStepTests JSON vectors give {@code 2*(extensions)} instead, i.e. this
     * value minus {@code 2 + delta}: they disagree on 3 modes of 5. The hardware decides:
     * the {@code expected000} values of vAmigaTS {@code CPU/Exceptions/StackFrame}, measured
     * on a real A500, agree with this rule. The same arbitration as for Bcc in
     * {@code docs/castle-master-copylock-investigation.md}, cause 6.
     */
    private int group0DataFaultPcOffset() {
        int delta = group0EaDeltaOverride != Integer.MIN_VALUE
                ? group0EaDeltaOverride
                : switch (group0EaMode) {
                    // (d16,An), (d8,An,Xn), (d16,PC), (d8,PC,Xn): the extension word of the
                    // failing EA is not counted yet
                    case 5, 6, 10, 11 -> -2;
                    // -(An): on the 68000 byte and word count one word more, long does not;
                    // the 68010 counts no extra word
                    case 4 -> group0EaSize == 4 || isM68010() ? 0 : 2;
                    default -> 0;
                };
        return 2 + ((extensionsConsumed - 1) * 2) + delta;
    }
