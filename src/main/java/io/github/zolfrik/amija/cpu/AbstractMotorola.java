    /**
     * Phase of the E clock (phi2/10) that drives the {@code S_VMA} machine.
     *
     * <p><b>It starts at 9, not 0, and the master cycle of difference is a PHASE, not a
     * delay.</b> On the 68000 the E clock is generated by the processor itself dividing CLK
     * by 10, on the same grid as the chip bus: a synchronous cycle always starts and ends on
     * a CCK edge and lasts an even number of master cycles (sync 1 CCK, start 2 CCK, end
     * 3 CCK, period 5 CCK).
     *
     * <p>Starting at 0 would put phase 2 on a master cycle of the wrong parity with respect
     * to the chip-bus grid: the synchronous cycle would last <b>15</b> master cycles (half a
     * CCK, a length the hardware cannot produce) instead of 16, and the prefetch after it
     * would pay one to realign (5 instead of 4). The two errors cancel with a free bus, which
     * is why the total of a {@code MOVE.L} from CIA space stays right, but not under DMA
     * contention: that master cycle moves the access into another slot. Measured on vAmigaTS
     * {@code Memory/Ram/memtim1}: the three CIA regions went from +620/+80/+60 pixels to
     * <b>bit-exact, iteration by iteration</b>.
     *
     * <p><b>It goes together with the anchor of {@code SLOT_CIAA}</b> in
     * {@code AbstractAgnus} ({@code masterClock + 9}): on silicon it is one wire, and moving
     * one counter without the other splits it in two. The invariant "the CIA ticks at
     * {@code eClockCounter == 0}" is frozen by {@code CiaEClockPhaseTest}.
     * See {@code docs/vamigats-import-order.md}, {@code memtim1} outcomes.
     */
    private int eClockCounter = 9;
